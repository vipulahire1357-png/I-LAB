"""
Occupancy Manager (Module 5).

Accumulates crossing events into persistent classroom occupancy counters,
enforces non-negative invariants, and determines the high-level OCCUPIED/EMPTY state.
"""

from __future__ import annotations

import logging
from typing import List, Optional

from src.counting.models import CrossingEvent, EventType
from src.occupancy.models import ClassroomState, OccupancyState

logger = logging.getLogger(__name__)


class OccupancyManager:
    """Manages real-time occupancy counts and operational state transitions.

    Parameters
    ----------
    initial_occupancy : int
        Starting occupancy count (default 0).
    """

    def __init__(self, initial_occupancy: int = 0) -> None:
        self._occupancy_count = max(0, initial_occupancy)
        self._occupancy_approximation = 0
        self._total_entries = 0
        self._total_exits = 0
        self._left_occupancy = 0
        self._right_occupancy = 0
        self._left_divider_count = 0
        self._right_divider_count = 0
        self._left_area_count = 0
        self._right_area_count = 0
        self._last_state: ClassroomState = (
            ClassroomState.OCCUPIED if self._occupancy_count > 0 else ClassroomState.EMPTY
        )
        self._state_changed: bool = False

    @property
    def occupancy_count(self) -> int:
        """Current estimated occupancy count strictly decided by counting line (guaranteed >= 0)."""
        return self._occupancy_count

    @property
    def occupancy_approximation(self) -> int:
        """Current occlusion uncertainty approximation (0 for ±0, 1 for ±1, 2 for ±2)."""
        return self._occupancy_approximation

    @property
    def total_entries(self) -> int:
        """Cumulative confirmed entries."""
        return self._total_entries

    @property
    def total_exits(self) -> int:
        """Cumulative confirmed exits."""
        return self._total_exits

    @property
    def left_occupancy(self) -> int:
        """Real-time occupant count on the left side of the perpendicular divider."""
        return self._left_occupancy

    @property
    def right_occupancy(self) -> int:
        """Real-time occupant count on the right side of the perpendicular divider."""
        return self._right_occupancy

    @property
    def left_area_count(self) -> int:
        """Visible occupant count in Left Seating Area."""
        return self._left_area_count

    @property
    def right_area_count(self) -> int:
        """Visible occupant count in Right Seating Area."""
        return self._right_area_count

    @property
    def classroom_state(self) -> ClassroomState:
        """Current operational state (OCCUPIED or EMPTY)."""
        return ClassroomState.OCCUPIED if self._occupancy_count > 0 else ClassroomState.EMPTY

    @property
    def state_changed(self) -> bool:
        """Whether the classroom state transitioned in the most recent update."""
        return self._state_changed

    def apply(
        self,
        events: List[CrossingEvent],
        approximation: int = 0,
        left_area_count: int = 0,
        right_area_count: int = 0,
        left_occupancy: Optional[int] = None,
        right_occupancy: Optional[int] = None,
        tracked_boxes: Optional[List[tuple]] = None,
    ) -> OccupancyState:
        """Apply a batch of line crossing events and update zone occupancy for the current frame.

        Parameters
        ----------
        events : list[CrossingEvent]
            Confirmed crossing events generated by the EntryExitCounter.
        approximation : int
            Occlusion uncertainty approximation (0 for ±0, 1 for ±1, 2 for ±2).
        left_area_count : int
            Spatial presence count of detected people in Left Seating Area.
        right_area_count : int
            Spatial presence count of detected people in Right Seating Area.
        left_occupancy : int | None
            Optional override for testing only.
        right_occupancy : int | None
            Optional override for testing only.

        Returns
        -------
        OccupancyState
            Updated occupancy state snapshot.
        """
        for event in events:
            if event.event_type == EventType.ENTER:
                self._total_entries += 1
                self._occupancy_count += 1
                if event.side == "LEFT":
                    self._left_occupancy += 1
                elif event.side == "RIGHT":
                    self._right_occupancy += 1

                logger.debug(
                    "Occupancy incremented to %d (left=%d, right=%d, total_entries=%d)",
                    self._occupancy_count,
                    self._left_occupancy,
                    self._right_occupancy,
                    self._total_entries,
                )

            elif event.event_type == EventType.EXIT:
                self._total_exits += 1
                self._occupancy_count = max(0, self._occupancy_count - 1)
                if event.side == "LEFT":
                    if self._left_occupancy > 0:
                        self._left_occupancy -= 1
                    elif self._right_occupancy > 0:
                        self._right_occupancy -= 1
                elif event.side == "RIGHT":
                    if self._right_occupancy > 0:
                        self._right_occupancy -= 1
                    elif self._left_occupancy > 0:
                        self._left_occupancy -= 1
                else:
                    if self._left_occupancy > 0:
                        self._left_occupancy -= 1
                    elif self._right_occupancy > 0:
                        self._right_occupancy -= 1

                logger.debug(
                    "Occupancy decremented to %d (left=%d, right=%d, total_exits=%d)",
                    self._occupancy_count,
                    self._left_occupancy,
                    self._right_occupancy,
                    self._total_exits,
                )

            elif event.event_type == EventType.ZONE_ENTER_LEFT:
                self._left_divider_count += 1
                self._left_occupancy += 1
                logger.debug("Zone ENTER LEFT: left=%d, divider_left=%d", self._left_occupancy, self._left_divider_count)

            elif event.event_type == EventType.ZONE_EXIT_LEFT:
                self._left_divider_count = max(0, self._left_divider_count - 1)
                self._left_occupancy = max(0, self._left_occupancy - 1)
                logger.debug("Zone EXIT LEFT: left=%d, divider_left=%d", self._left_occupancy, self._left_divider_count)

            elif event.event_type == EventType.ZONE_ENTER_RIGHT:
                self._right_divider_count += 1
                self._right_occupancy += 1
                logger.debug("Zone ENTER RIGHT: right=%d, divider_right=%d", self._right_occupancy, self._right_divider_count)

            elif event.event_type == EventType.ZONE_EXIT_RIGHT:
                self._right_divider_count = max(0, self._right_divider_count - 1)
                self._right_occupancy = max(0, self._right_occupancy - 1)
                logger.debug("Zone EXIT RIGHT: right=%d, divider_right=%d", self._right_occupancy, self._right_divider_count)

            elif event.event_type == EventType.ZONE_CROSS_LEFT_TO_RIGHT:
                self._left_divider_count = max(0, self._left_divider_count - 1)
                self._right_divider_count += 1
                if self._left_occupancy > 0:
                    self._left_occupancy -= 1
                self._right_occupancy += 1
                logger.debug(
                    "Zone cross LEFT -> RIGHT: left=%d, right=%d",
                    self._left_occupancy,
                    self._right_occupancy,
                )

            elif event.event_type == EventType.ZONE_CROSS_RIGHT_TO_LEFT:
                self._right_divider_count = max(0, self._right_divider_count - 1)
                self._left_divider_count += 1
                if self._right_occupancy > 0:
                    self._right_occupancy -= 1
                self._left_occupancy += 1
                logger.debug(
                    "Zone cross RIGHT -> LEFT: left=%d, right=%d",
                    self._left_occupancy,
                    self._right_occupancy,
                )
        if tracked_boxes is not None:
            self._occupancy_count = len(tracked_boxes)
        self._occupancy_approximation = max(0, min(2, int(approximation)))
        self._left_area_count = max(0, int(left_area_count))
        self._right_area_count = max(0, int(right_area_count))

        if left_occupancy is not None:
            self._left_occupancy = max(0, left_occupancy)
        if right_occupancy is not None:
            self._right_occupancy = max(0, right_occupancy)

        # Enforce conservation invariant
        self._occupancy_count = max(0, self._occupancy_count)
        self._left_occupancy = max(0, self._left_occupancy)
        self._right_occupancy = max(0, self._right_occupancy)

        if self._occupancy_count == 0 and left_occupancy is None and right_occupancy is None:
            self._left_occupancy = 0
            self._right_occupancy = 0
        elif left_occupancy is None and right_occupancy is None:
            # Rebalance if sum exceeds total room occupancy
            current_sum = self._left_occupancy + self._right_occupancy
            if current_sum > self._occupancy_count:
                excess = current_sum - self._occupancy_count
                if self._left_occupancy >= excess:
                    self._left_occupancy -= excess
                else:
                    remaining = excess - self._left_occupancy
                    self._left_occupancy = 0
                    self._right_occupancy = max(0, self._right_occupancy - remaining)

        current_state = self.classroom_state

        self._state_changed = current_state != self._last_state
        if self._state_changed:
            logger.info(
                "Classroom state transitioned: %s -> %s (occupancy=%d (±%d), left_area=%d, right_area=%d)",
                self._last_state.value,
                current_state.value,
                self._occupancy_count,
                self._occupancy_approximation,
                self._left_area_count,
                self._right_area_count,
            )
            self._last_state = current_state

        return self.get_state()

    def get_state(self) -> OccupancyState:
        """Return an immutable snapshot of current occupancy."""
        left_area_st = ClassroomState.OCCUPIED if self._left_area_count > 0 else ClassroomState.EMPTY
        right_area_st = ClassroomState.OCCUPIED if self._right_area_count > 0 else ClassroomState.EMPTY
        left_div_st = ClassroomState.OCCUPIED if self._left_divider_count > 0 else ClassroomState.EMPTY
        right_div_st = ClassroomState.OCCUPIED if self._right_divider_count > 0 else ClassroomState.EMPTY
        left_st = ClassroomState.OCCUPIED if (self._left_area_count > 0 or self._left_occupancy > 0) else ClassroomState.EMPTY
        right_st = ClassroomState.OCCUPIED if (self._right_area_count > 0 or self._right_occupancy > 0) else ClassroomState.EMPTY
        walkway_occ = max(0, self._occupancy_count - self._left_occupancy - self._right_occupancy)

        return OccupancyState(
            occupancy_count=self._occupancy_count,
            occupancy_approximation=self._occupancy_approximation,
            total_entries=self._total_entries,
            total_exits=self._total_exits,
            classroom_state=self.classroom_state,
            left_area_state=left_area_st,
            right_area_state=right_area_st,
            left_area_count=self._left_area_count,
            right_area_count=self._right_area_count,
            left_divider_state=left_div_st,
            right_divider_state=right_div_st,
            left_divider_count=self._left_divider_count,
            right_divider_count=self._right_divider_count,
            left_occupancy=self._left_occupancy,
            right_occupancy=self._right_occupancy,
            walkway_occupancy=walkway_occ,
            left_state=left_st,
            right_state=right_st,
        )

    def reset(self, initial_occupancy: int = 0) -> None:
        """Reset all counters and state."""
        self._occupancy_count = max(0, initial_occupancy)
        self._occupancy_approximation = 0
        self._total_entries = 0
        self._total_exits = 0
        self._left_occupancy = 0
        self._right_occupancy = 0
        self._left_divider_count = 0
        self._right_divider_count = 0
        self._left_area_count = 0
        self._right_area_count = 0
        self._last_state = (
            ClassroomState.OCCUPIED if self._occupancy_count > 0 else ClassroomState.EMPTY
        )
        self._state_changed = False
        logger.info("OccupancyManager reset (initial_occupancy=%d)", self._occupancy_count)

    def __repr__(self) -> str:
        return (
            f"OccupancyManager(occupancy={self._occupancy_count}±{self._occupancy_approximation}, "
            f"left_area={self._left_area_count}, right_area={self._right_area_count}, "
            f"entries={self._total_entries}, exits={self._total_exits}, "
            f"state={self.classroom_state.value})"
        )
